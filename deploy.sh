#!/bin/bash

################################################################################
# Multi-Cloud GPU Terraform Deployment Wrapper
# 
# This script provides a simplified interface for deploying GPU infrastructure
# to AWS, Azure, or GCP with automatic NVIDIA driver and CUDA installation.
#
# Usage: ./deploy.sh
################################################################################

set -e

# Colors for output
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
NC='\033[0m' # No Color

# Configuration
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
TERRAFORM_DIR="$SCRIPT_DIR"

# Cleanup on exit
cleanup() {
  if [ $? -ne 0 ]; then
    echo -e "${RED}✗ Deployment failed!${NC}"
  fi
}
trap cleanup EXIT

################################################################################
# Helper Functions
################################################################################

print_header() {
  echo -e "${BLUE}═══════════════════════════════════════════════════════════════${NC}"
  echo -e "${BLUE}$1${NC}"
  echo -e "${BLUE}═══════════════════════════════════════════════════════════════${NC}"
}

print_success() {
  echo -e "${GREEN}✓ $1${NC}"
}

print_error() {
  echo -e "${RED}✗ $1${NC}"
}

print_info() {
  echo -e "${YELLOW}ℹ $1${NC}"
}

prompt_with_default() {
  local prompt="$1"
  local default="$2"
  local input
  
  read -p "$prompt [$default]: " input
  echo "${input:-$default}"
}

validate_cloud_provider() {
  case "$1" in
    aws|azure|gcp)
      return 0
      ;;
    *)
      print_error "Invalid cloud provider. Must be: aws, azure, or gcp"
      return 1
      ;;
  esac
}

validate_aws_region() {
  # AWS supports these regions for GPU instances
  local region="$1"
  case "$region" in
    ap-south-1|ap-south-2|us-east-1|us-west-2|eu-west-1)
      return 0
      ;;
    *)
      print_info "Using custom region: $region (verify g5.4xlarge availability)"
      return 0
      ;;
  esac
}

validate_azure_region() {
  # Common Azure regions
  local region="$1"
  case "$region" in
    eastus|westus|westus2|eastus2|southcentralus|centralus|northeurope|westeurope)
      return 0
      ;;
    *)
      print_info "Using custom region: $region (verify Standard_NV36ads_A10_v5 availability)"
      return 0
      ;;
  esac
}

validate_gcp_region() {
  # GCP regions with GPU availability
  local region="$1"
  case "$region" in
    us-central1|us-west1|us-east1|europe-west1|asia-east1)
      return 0
      ;;
    *)
      print_info "Using custom region: $region (verify g2-standard-16 availability)"
      return 0
      ;;
  esac
}

check_terraform() {
  if ! command -v terraform &> /dev/null; then
    print_error "Terraform is not installed. Please install Terraform first."
    echo "Visit: https://www.terraform.io/downloads"
    exit 1
  fi
  
  local tf_version=$(terraform version | head -n 1)
  print_success "Found $tf_version"
}

check_terraform_files() {
  local required_files=("main.tf" "variables.tf" "outputs.tf" "providers.tf")
  
  for file in "${required_files[@]}"; do
    if [ ! -f "$TERRAFORM_DIR/$file" ]; then
      print_error "Required file not found: $file"
      exit 1
    fi
  done
  
  print_success "All Terraform files found"
}

initialize_terraform() {
  print_info "Initializing Terraform..."
  cd "$TERRAFORM_DIR"
  terraform init -upgrade
  print_success "Terraform initialized"
}

validate_terraform() {
  print_info "Validating Terraform configuration..."
  cd "$TERRAFORM_DIR"
  terraform validate
  print_success "Terraform configuration is valid"
}

create_tfvars() {
  local cloud_provider="$1"
  local region="$2"
  local vm_name="$3"
  local ssh_key="$4"
  local project_id="$5"
  local git_username="$6"
  local git_password="$7"
  
  local tfvars_file="$TERRAFORM_DIR/terraform.tfvars"
  
  cat > "$tfvars_file" << EOF
# Auto-generated by deploy.sh
# Generated: $(date)

cloud_provider = "$cloud_provider"
region         = "$region"
vm_name        = "$vm_name"
git_username   = "$git_username"
git_password   = "$git_password"
EOF

  case "$cloud_provider" in
    aws)
      echo "aws_certificate_arn = null" >> "$tfvars_file"
      ;;
    azure)
      if [ -n "$ssh_key" ]; then
        echo "azure_ssh_public_key = \"$ssh_key\"" >> "$tfvars_file"
      fi
      ;;
    gcp)
      if [ -n "$project_id" ]; then
        echo "gcp_project_id = \"$project_id\"" >> "$tfvars_file"
      fi
      ;;
  esac
  
  print_success "Created terraform.tfvars"
}

show_plan() {
  print_info "Generating Terraform plan..."
  cd "$TERRAFORM_DIR"
  terraform plan -no-color | tee /tmp/deploy_plan.txt
}

confirm_deployment() {
  echo ""
  read -p "Do you want to apply this plan? (yes/no): " confirm
  
  if [ "$confirm" != "yes" ]; then
    print_info "Deployment cancelled"
    exit 0
  fi
}

apply_terraform() {
  print_info "Applying Terraform configuration..."
  cd "$TERRAFORM_DIR"
  terraform apply -auto-approve
  print_success "Infrastructure deployed successfully!"
}

show_outputs() {
  print_header "Deployment Outputs"
  
  cd "$TERRAFORM_DIR"
  terraform output -json 2>/dev/null | jq . || true
}

