################################################################################
# Main Script
################################################################################

main() {
  print_header "Multi-Cloud GPU Terraform Deployment"
  
  # Check prerequisites
  print_info "Checking prerequisites..."
  check_terraform
  check_terraform_files
  
  # Prompt for configuration
  echo ""
  print_header "Configuration"
  
  # Cloud provider selection
  while true; do
    cloud_provider=$(prompt_with_default "Cloud provider (aws/azure/gcp)" "aws")
    if validate_cloud_provider "$cloud_provider"; then
      break
    fi
  done
  
  # Region selection
  case "$cloud_provider" in
    aws)
      region=$(prompt_with_default "AWS region" "ap-south-1")
      validate_aws_region "$region"
      ;;
    azure)
      region=$(prompt_with_default "Azure region" "eastus")
      validate_azure_region "$region"
      ;;
    gcp)
      region=$(prompt_with_default "GCP region" "us-central1")
      validate_gcp_region "$region"
      ;;
  esac
  
  # VM name
  vm_name=$(prompt_with_default "VM/Instance name" "gpu-server")
  
  # Git credentials for private repositories
  echo ""
  print_header "Git Credentials (for Private Repositories)"
  print_info "If you need to deploy private repositories, provide credentials."
  print_info "Otherwise, leave empty for public repositories only."
  echo ""
  
  read -p "Git username/email (leave empty if not needed): " git_username
  if [ -n "$git_username" ]; then
    read -s -p "Git password/token: " git_password
    echo ""
    print_success "Git credentials saved (will be securely passed to instances)"
  else
    git_password=""
    print_info "Skipping Git credentials - will only deploy public repositories"
  fi
  
  # Cloud-specific prompts
  ssh_key=""
  project_id=""
  
  if [ "$cloud_provider" = "azure" ]; then
    echo ""
    print_info "Enter your SSH public key (leave empty to use placeholder):"
    read -p "SSH public key: " ssh_key
  fi
  
  if [ "$cloud_provider" = "gcp" ]; then
    echo ""
    project_id=$(prompt_with_default "GCP Project ID" "")
  fi
  
  # Initialize and validate
  print_header "Initialization"
  initialize_terraform
  
  echo ""
  validate_terraform
  
  # Create terraform.tfvars
  echo ""
  create_tfvars "$cloud_provider" "$region" "$vm_name" "$ssh_key" "$project_id" "$git_username" "$git_password"
  
  # Show plan
  echo ""
  show_plan
  
  # Confirm and apply
  echo ""
  confirm_deployment
  
  apply_terraform
  
  # Show outputs
  echo ""
  show_outputs
  
  # Show next steps
  show_next_steps "$cloud_provider"
  
  print_success "Deployment script completed!"
}

# Run main function
main "$@"
